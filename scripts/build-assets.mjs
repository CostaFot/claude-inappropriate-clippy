#!/usr/bin/env node
// Builds hooks/book.ts and hooks/sprites.ts from the Omarchy plugin's
// quotes.json and sprite atlas. The hooks module cannot import JSON or read
// the atlas in a test, so both are baked into TypeScript here.
//
//   scripts/build-assets.mjs [path to omarchy-inappropriate-clippy]
//
// Needs ImageMagick (`magick`). Both outputs are generated: edit this script
// or the Omarchy repo's quotes.json, never the .ts files.

import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(dirname(fileURLToPath(import.meta.url)))
const omarchy = process.argv[2] ?? join(homedir(), 'Work/omarchy-inappropriate-clippy')

// The categories this mod speaks from. `reactions` (window-title regexes)
// and the drag/fling lines are the bar's business, not ours.
const KEYS = ['quotes', 'comeback', 'lastWords', 'slapped', 'knockedOut', 'welcomeBack', 'epitaph', 'dodged']

const quotes = JSON.parse(readFileSync(join(omarchy, 'quotes.json'), 'utf8'))
const book = {}
for (const key of KEYS) {
  book[key] = quotes[key].map(q =>
    typeof q === 'string' ? { text: q, nsfw: false } : { text: q.text, nsfw: q.nsfw === true, ...(q.anim ? { anim: q.anim } : {}) },
  )
}

// Every animation a line names, plus the ones the mod plays on its own.
const anims = new Set(['RestPose', 'Alert', 'GetAttention', 'GoodBye', 'Wave', 'Explain', 'Thinking', 'Writing', 'Searching'])
for (const key of KEYS) for (const q of book[key]) if (q.anim) anims.add(q.anim)

const agent = JSON.parse(readFileSync(join(omarchy, 'assets/clippy/agent.json'), 'utf8'))
const [w, h] = agent.framesize
const atlas = join(omarchy, 'assets/clippy/map.png')
// A Svg's source is capped at 131072 characters; the strip's base64 plus the
// markup around it has to fit.
const BUDGET = 118000

const tmp = mkdtempSync(join(tmpdir(), 'clippy-assets-'))
const sprites = {}
try {
  for (const name of [...anims].sort()) {
    const anim = agent.animations[name]
    if (!anim) throw new Error(`no animation ${name} in agent.json`)
    // Collapse runs of the same image into one frame with the summed duration;
    // a frame with no image is a blank one.
    let frames = []
    for (const f of anim.frames) {
      const at = f.images?.[0] ?? null
      const id = at ? at.join(',') : 'blank'
      const last = frames.at(-1)
      if (last && last.id === id) last.ms += f.duration
      else frames.push({ id, at, ms: f.duration })
    }
    let step = 1
    let png
    for (;;) {
      const kept = frames.filter((_, i) => i % step === 0 || i === frames.length - 1)
      const ms = kept.map((f, i) => {
        // Dropped frames give their time to the frame kept before them.
        const from = frames.indexOf(f)
        const to = i + 1 < kept.length ? frames.indexOf(kept[i + 1]) : frames.length
        return frames.slice(from, to).reduce((s, x) => s + x.ms, 0)
      })
      const out = join(tmp, `${name}.png`)
      const args = [atlas]
      for (const f of kept) {
        if (f.at) args.push('(', '-clone', '0', '-crop', `${w}x${h}+${f.at[0]}+${f.at[1]}`, '+repage', ')')
        else args.push('(', '-size', `${w}x${h}`, 'xc:none', ')')
      }
      args.push('-delete', '0', '+append', '-strip', `png8:${out}`)
      execFileSync('magick', args)
      png = readFileSync(out).toString('base64')
      if (png.length <= BUDGET || step > 6) {
        sprites[name] = { frames: kept.length, ms, png }
        break
      }
      step += 1
    }
    if (png.length > BUDGET) throw new Error(`${name} does not fit even at every ${step}th frame`)
  }
} finally {
  rmSync(tmp, { recursive: true, force: true })
}

const banner = '// Generated by scripts/build-assets.mjs. Do not edit.\n'
writeFileSync(
  join(here, 'hooks/book.ts'),
  `${banner}import type { Line } from '../types'\n\nexport const BOOK: Record<${KEYS.map(k => `'${k}'`).join(' | ')}, readonly Line[]> = ${JSON.stringify(book, null, 2)}\n`,
)
// One file per animation: the engine reads no module file over 1 MiB.
const dir = join(here, 'hooks/sprites')
rmSync(dir, { recursive: true, force: true })
mkdirSync(dir)
const names = Object.keys(sprites)
for (const name of names) {
  writeFileSync(join(dir, `${name}.ts`), `${banner}export const ${name} = ${JSON.stringify(sprites[name])}\n`)
}
writeFileSync(
  join(here, 'hooks/sprites.ts'),
  `${banner}${names.map(n => `import { ${n} } from './sprites/${n}'`).join('\n')}\n\n` +
    `export const FRAME = { width: ${w}, height: ${h} } as const\n\n` +
    `export const SPRITES: Record<string, { frames: number; ms: readonly number[]; png: string }> = { ${names.join(', ')} }\n`,
)

const total = Object.values(sprites).reduce((s, x) => s + x.png.length, 0)
console.log(`${Object.values(book).flat().length} lines, ${Object.keys(sprites).length} animations, ${Math.round(total / 1024)} KiB of sprites`)
for (const [name, s] of Object.entries(sprites)) console.log(`  ${name}: ${s.frames} frames, ${Math.round(s.png.length / 1024)} KiB`)
